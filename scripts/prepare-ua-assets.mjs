import { mkdir, readdir, copyFile, writeFile } from "node:fs/promises";
import sharp from "sharp";
await mkdir("public/ua", { recursive: true });
// Re-encode artwork to remove Canva account/person metadata. No populated
// schedule image, workbook, or trainer data is copied into public assets.
await sharp("example/blank background/LIVE.png")
  .png()
  .toFile("public/ua/background.png");
await sharp("example/Copy of UA  Weekly Schedule STORY/COVER.png")
  .png()
  .toFile("public/ua/cover.png");
const fonts = {};
async function visit(path) {
  for (const entry of await readdir(path, { withFileTypes: true })) {
    const file = `${path}/${entry.name}`;
    if (entry.isDirectory()) {
      await visit(file);
      continue;
    }
    if (!/gotham/i.test(entry.name) || !/\.(otf|ttf|woff2?)$/i.test(entry.name))
      continue;
    const role = /italic|oblique/i.test(entry.name)
      ? "italic"
      : /black|ultra/i.test(entry.name)
        ? "black"
        : /bold/i.test(entry.name)
          ? "bold"
          : /book|regular/i.test(entry.name)
            ? "regular"
            : "";
    if (!role || fonts[role]) continue;
    const extension = entry.name.match(/\.[^.]+$/)[0];
    const filename = `gotham-${role}${extension}`;
    await copyFile(file, `public/ua/${filename}`);
    fonts[role] = `ua/${filename}`;
  }
}
await visit("example");
await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/uaFonts.ts",
  `// Generated by scripts/prepare-ua-assets.mjs\nexport const bundledGotham: Partial<Record<'regular' | 'bold' | 'black' | 'italic', string>> = ${JSON.stringify(fonts, null, 2)};\n`,
);
console.log("UA blank artwork prepared without source metadata.");
